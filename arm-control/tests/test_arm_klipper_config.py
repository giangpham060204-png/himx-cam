"""Generated Klipper config tests."""

import dataclasses
import pathlib
import sys

import pytest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from src.config import load_config  # noqa: E402
from src.errors import ConfigError  # noqa: E402
from src.klipper_config import (  # noqa: E402
    generate_printer_config,
    write_printer_config,
)

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONFIG = load_config(ROOT / "src" / "config" / "arm.toml")


def test_generated_config_has_three_steppers_and_three_tmc_sections():
    text = generate_printer_config(CONFIG)

    assert text.count("[manual_stepper ") == 3
    assert text.count("[tmc2209 manual_stepper ") == 3
    assert "kinematics: none" in text
    assert "serial: /dev/serial/by-id/usb-Klipper_rp2040_E66164084383A533-if00" in text
    assert text.count("position_min: -21") == 2
    assert "position_max: 221" in text
    assert "position_min: -361" in text
    assert "position_max: 361" in text
    assert "position_max: 121" in text
    assert "endstop_pin: ^gpio13" in text
    assert "rotation_distance: 360" in text
    assert "gear_ratio" not in text
    assert "run_current: 1" in text


def test_tmc_sections_can_be_omitted_for_the_simulator():
    text = generate_printer_config(CONFIG, include_tmc=False)

    assert "[tmc2209" not in text


def test_inverted_dir_and_endstop_are_rendered():
    axis = dataclasses.replace(
        CONFIG.axes["m1"], invert_dir=True, endstop_inverted=True
    )
    config = dataclasses.replace(CONFIG, axes={**CONFIG.axes, "m1": axis})
    text = generate_printer_config(config)

    assert "dir_pin: !gpio3" in text
    assert "endstop_pin: ^!gpio13" in text


def test_gear_ratio_is_emitted_when_not_one():
    axis = dataclasses.replace(CONFIG.axes["m1"], gear_ratio=2.0)
    config = dataclasses.replace(CONFIG, axes={**CONFIG.axes, "m1": axis})
    text = generate_printer_config(config)

    assert "gear_ratio: 2:1" in text


def test_home_target_is_inside_klipper_outer_limits():
    for axis in CONFIG.axes.values():
        assert axis.klipper_min <= axis.home_target() <= axis.klipper_max


def test_write_refuses_to_overwrite_without_force(tmp_path):
    path = tmp_path / "printer.cfg"
    write_printer_config(CONFIG, path)

    with pytest.raises(ConfigError, match="already exists"):
        write_printer_config(CONFIG, path)

    write_printer_config(CONFIG, path, force=True)
    assert path.read_text().startswith("# Generated by src.klipper_config")


def test_generated_config_is_stable():
    assert generate_printer_config(CONFIG) == generate_printer_config(CONFIG)
