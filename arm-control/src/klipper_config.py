"""Generate a Klipper printer.cfg from the arm TOML config."""

from __future__ import annotations

from pathlib import Path

from .commands import format_number
from .config import AXIS_NAMES, RobotConfig
from .errors import ConfigError


def _dir_pin(axis) -> str:
    return ("!" if axis.invert_dir else "") + axis.dir_pin


def _enable_pin(axis) -> str:
    return ("!" if axis.enable_active_low else "") + axis.enable_pin


def _endstop_pin(axis) -> str:
    prefix = "^" if axis.endstop_pullup else ""
    if axis.endstop_inverted:
        prefix += "!"
    return prefix + axis.endstop_pin


def generate_printer_config(
    config: RobotConfig, include_tmc: bool = True
) -> str:
    lines = [
        "# Generated by src.klipper_config; do not edit.",
        f"# config_hash: {config.config_hash}",
        f"# stack: {config.stack}",
        "",
        "[printer]",
        "kinematics: none",
        "max_velocity: 1",
        "max_accel: 1",
        "",
        "[mcu]",
        f"serial: {config.serial}",
        "",
    ]

    for name in AXIS_NAMES:
        axis = config.axes[name]
        lines.extend(
            [
                f"[manual_stepper {name}]",
                f"step_pin: {axis.step_pin}",
                f"dir_pin: {_dir_pin(axis)}",
                f"enable_pin: {_enable_pin(axis)}",
                f"microsteps: {axis.microsteps}",
                f"full_steps_per_rotation: {axis.full_steps_per_rev}",
                f"rotation_distance: {format_number(axis.units_per_rev)}",
            ]
        )
        if axis.gear_ratio != 1.0:
            lines.append(f"gear_ratio: {format_number(axis.gear_ratio)}:1")
        lines.extend(
            [
                f"endstop_pin: {_endstop_pin(axis)}",
                f"position_min: {format_number(axis.klipper_min)}",
                f"position_max: {format_number(axis.klipper_max)}",
                f"velocity: {format_number(axis.max_speed)}",
                f"accel: {format_number(axis.max_accel)}",
                "",
            ]
        )
        if include_tmc:
            lines.extend(
                [
                    f"[tmc2209 manual_stepper {name}]",
                    f"uart_pin: {axis.uart_pin}",
                    f"tx_pin: {axis.tx_pin}",
                    f"uart_address: {axis.uart_address}",
                    f"run_current: {format_number(axis.run_current)}",
                    "interpolate: False",
                    "stealthchop_threshold: 0",
                    "",
                ]
            )

    return "\n".join(lines).rstrip() + "\n"


def write_printer_config(
    config: RobotConfig,
    path: str | Path,
    include_tmc: bool = True,
    force: bool = False,
) -> Path:
    path = Path(path)
    if path.exists() and not force:
        raise ConfigError(
            f"{path} already exists; pass force=True to overwrite it"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        generate_printer_config(config, include_tmc=include_tmc),
        encoding="utf-8",
    )
    return path
